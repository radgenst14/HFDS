/**
 * Requirement → scenario / test matrix (doc 14 "Coverage rule", doc 15 B2, doc 17 M6).
 *
 * Sources:
 *   - docs/requirements.json (all SRS §3 items with their prototype treatment)
 *   - test-name tags in tests/**\/*.ts matching [R…], [SR…], [IR…] (IR29b allowed)
 *   - each preset's `requirements` (demonstrates) and `expect[].reqs` (verifies)
 *
 * Usage:
 *   npm run trace                     # Markdown matrix to stdout
 *   npm run trace -- --out docs/trace-matrix.md
 *   npm run trace -- --strict         # exit 1 if a SIM requirement has no test/expectation
 *
 * M0 version: complete matrix, but CI runs --strict only from M6 onward.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

interface Requirement {
  id: string;
  section: string;
  text: string;
  prototype: { treatment: 'SIM' | 'STUB' | 'HMI' | 'LOG' | 'DOC'; how: string; scenarios: string };
}

const ROOT = join(import.meta.dirname, '..');
const TAG = /\[((?:R|SR|IR)\d+(?:\.\d+)*b?)\]/g;

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(test|spec)\.ts$/.test(name)) out.push(p);
  }
  return out;
}

const add = (map: Map<string, Set<string>>, id: string, where: string) => {
  if (!map.has(id)) map.set(id, new Set());
  map.get(id)?.add(where);
};

/** A tag on a parent ID (R29) does not cover children (R29.3); a child tag counts for its parent. */
function coveredBy(map: Map<string, Set<string>>, id: string): string[] {
  const hits = new Set<string>();
  for (const [key, where] of map) {
    if (key === id || key.startsWith(`${id}.`)) where.forEach((w) => hits.add(w));
  }
  return [...hits].sort();
}

export function buildMatrix(): { markdown: string; uncoveredSim: string[] } {
  const reqs = JSON.parse(
    readFileSync(join(ROOT, 'docs', 'requirements.json'), 'utf8'),
  ) as Requirement[];

  const testTags = new Map<string, Set<string>>();
  for (const file of walk(join(ROOT, 'tests'))) {
    const rel = relative(ROOT, file).replaceAll('\\', '/');
    for (const m of readFileSync(file, 'utf8').matchAll(TAG)) if (m[1]) add(testTags, m[1], rel);
  }

  const demonstrates = new Map<string, Set<string>>();
  const verifies = new Map<string, Set<string>>();
  const scenarioDir = join(ROOT, 'public', 'scenarios');
  for (const file of readdirSync(scenarioDir).filter((f) => /^s\d\d-.*\.json$/.test(f))) {
    const s = JSON.parse(readFileSync(join(scenarioDir, file), 'utf8')) as {
      id: string;
      requirements: string[];
      expect: Array<{ reqs: string[] }>;
    };
    const short = s.id.slice(0, 3).toUpperCase();
    s.requirements.forEach((id) => add(demonstrates, id, short));
    s.expect.forEach((e) => e.reqs.forEach((id) => add(verifies, id, short)));
  }

  const rows: string[] = [];
  const uncoveredSim: string[] = [];
  for (const r of reqs) {
    const tests = coveredBy(testTags, r.id);
    const expects = coveredBy(verifies, r.id);
    const demos = coveredBy(demonstrates, r.id);
    const tested = tests.length + expects.length > 0;
    if (r.prototype.treatment === 'SIM' && !tested) uncoveredSim.push(r.id);
    const status = tested ? 'tested' : demos.length ? 'demo only' : '—';
    rows.push(
      `| ${r.id} | ${r.prototype.treatment} | ${demos.join(', ') || '—'} | ${expects.join(', ') || '—'} | ${
        tests.join(', ') || '—'
      } | ${status} |`,
    );
  }

  const counts = reqs.reduce<Record<string, number>>((acc, r) => {
    acc[r.prototype.treatment] = (acc[r.prototype.treatment] ?? 0) + 1;
    return acc;
  }, {});

  const markdown = [
    '# Requirement trace matrix',
    '',
    `Generated by \`scripts/trace-matrix.ts\` from docs/requirements.json, test tags and scenario presets.`,
    '',
    `Requirements: ${reqs.length} (${Object.entries(counts)
      .map(([k, v]) => `${k} ${v}`)
      .join(', ')}). SIM requirements without a test or expectation: ${uncoveredSim.length}.`,
    '',
    '| ID | Treatment | Demonstrated in | Verified by expectations | Unit/e2e tests | Status |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');

  return { markdown, uncoveredSim };
}

function main(argv: string[]): void {
  const { markdown, uncoveredSim } = buildMatrix();
  const outIdx = argv.indexOf('--out');
  const out = outIdx >= 0 ? argv[outIdx + 1] : undefined;
  if (out) writeFileSync(join(ROOT, out), markdown);
  else process.stdout.write(markdown);
  if (argv.includes('--strict') && uncoveredSim.length > 0) {
    console.error(
      `Uncovered SIM requirements (${uncoveredSim.length}): ${uncoveredSim.join(', ')}`,
    );
    process.exit(1);
  }
}

main(process.argv.slice(2));
